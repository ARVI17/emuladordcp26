import {test,expect,openLocal,go} from './fixtures'
test('portada sin saldos inventados y navegación que conserva ruta, foco y sesión local',async({page},info)=>{
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'Inicio',exact:true})).toBeVisible()
 await expect(page.getByRole('region',{name:'Artículos sin asignar'})).toContainText('Sin consultar')
 await expect(page.locator('.account-facts')).toContainText('Cuenta no vinculada')
 expect(await page.evaluate(()=>document.documentElement.lang)).toBe('es')
 await page.screenshot({path:info.outputPath('inicio.png'),fullPage:true})
 await openLocal(page)
 await go(page,'Plantillas')
 await page.getByRole('navigation',{name:'Secciones de Plantillas'}).getByRole('button',{name:'Recomendadas',exact:true}).click()
 await expect(page).toHaveURL(/#\/plantillas\/recomendadas$/)
 await expect(page.getByRole('heading',{name:'Armar mi equipo',exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('heading',{name:'Armar mi equipo',exact:true})).toBeVisible()
 await expect(page.getByText(/Registro local sin vincular · Simulaciones/)).toBeVisible()
 await page.getByText('Ayúdame con esto',{exact:true}).click()
 await expect(page.getByText('Formación elegida: 4-3-3',{exact:true})).toBeVisible()
 await go(page,'Galería')
 await expect(page.getByRole('heading',{name:'Galería local',exact:true})).toBeVisible()
 await page.goBack()
 await expect(page.getByRole('heading',{name:'Armar mi equipo',exact:true})).toBeVisible()
 await expect(page.locator('#contenido')).toBeFocused()
 await page.goForward()
 await expect(page).toHaveURL(/#\/galeria$/)
 await expect(page.getByRole('heading',{name:'Galería local',exact:true})).toBeVisible()
 await go(page,'Tienda')
 await expect(page.getByText('Ofertas no disponibles',{exact:true})).toBeVisible()
 if(await page.getByRole('button',{name:'Abrir menú'}).isVisible()){
  await page.getByRole('button',{name:'Abrir menú'}).click()
  await expect(page.getByRole('dialog',{name:'Menú de secciones'})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
 }
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})
