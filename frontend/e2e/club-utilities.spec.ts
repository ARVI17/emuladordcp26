import {test,expect,openLocal,go} from './fixtures'

test('escenario de Galería y diario corregible conservan desconocidos y progreso EA',async({page,request},info)=>{
 const name=`Escenario sintético ${Date.now()}`
 const goalName=`Tarea sintética ${Date.now()}`
 const goal=await request.post('/api/objective-planning',{data:{name:goalName,target:3,phrase:'REVISAR OBJETIVO',rules:{source_reference:'Fixture sintético',source_text:'Ganar tres partidos de prueba',observed_at:new Date().toISOString(),reviewed:true,mode:'squad_battles',min_difficulty:'professional',loans_allowed:false,actions:[{id:'wins',kind:'wins',count:3,actor:'Equipo',source_text:'Ganar tres partidos'}]}}})
 expect(goal.ok()).toBeTruthy()
 const before=await goal.json()
 await openLocal(page);await go(page,'Galería')
 await page.getByRole('button',{name:'Definir escenario revisado',exact:true}).click()
 await page.getByLabel('Nombre del escenario',{exact:true}).fill(name)
 await page.getByLabel('Cartas exigidas',{exact:true}).fill('1')
 await page.getByRole('button',{name:'Añadir grado y premio',exact:true}).click()
 await page.getByLabel('Nombre del grado',{exact:true}).fill('C')
 await page.getByLabel('Puntos mínimos del grado',{exact:true}).fill('100')
 await page.getByLabel('Fichas del grado',{exact:true}).fill('5')
 await page.getByRole('button',{name:'Añadir bonificación porcentual',exact:true}).click()
 await page.getByLabel('Nombre de bonificación',{exact:true}).fill('Primer propietario desconocido en estas muestras')
 await page.getByRole('combobox',{name:'Atributo de bonificación',exact:true}).selectOption('first_owner')
 await page.getByRole('combobox',{name:'Valor que deben cumplir',exact:true}).selectOption('true')
 await page.getByLabel('Cantidad mínima del tramo 1',{exact:true}).fill('1')
 await page.getByLabel('Porcentaje del tramo 1',{exact:true}).fill('10')
 await page.getByLabel('Revisé las reglas, premios y multiplicidad de este escenario',{exact:true}).check()
 await page.getByRole('button',{name:'Guardar escenario revisado',exact:true}).click()
 const scenario=page.locator('article').filter({hasText:name})
 await expect(scenario).toBeVisible()
 await scenario.getByRole('checkbox').check()
 const declaring=page.waitForResponse(r=>r.url().endsWith('/declared-progress')&&r.request().method()==='PUT')
 await scenario.getByRole('button',{name:'Guardar declaración de progreso'}).click()
 expect((await declaring).ok()).toBeTruthy()
 await page.getByRole('button',{name:'Calcular ruta local revisable',exact:true}).click()
 await expect(page.getByText(/fichas adicionales conocidas: pendientes/)).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
 await page.screenshot({path:info.outputPath('gallery-v2-scenario.png'),fullPage:true})
 await go(page,'Planes')
 await page.getByText('Diario de partidos y práctica',{exact:true}).click()
 await page.getByText('Tareas de objetivos por partido',{exact:true}).click()
 await page.getByLabel(`${goalName}: Ganar tres partidos`,{exact:true}).fill('1')
 await page.getByLabel('Nota y condiciones revisadas',{exact:true}).fill('Resultado sintético declarado')
 const saving=page.waitForResponse(r=>r.url().includes('/objective-journal/')&&r.request().method()==='PUT')
 await page.getByRole('button',{name:'Guardar partida declarada',exact:true}).click()
 const response=await saving;expect(response.ok()).toBeTruthy()
 const match=await response.json()
 await page.reload()
 await page.getByText('Diario de partidos y práctica',{exact:true}).click()
 await page.getByText('Tareas de objetivos por partido',{exact:true}).click()
 await page.getByRole('combobox',{name:'Partida para corregir',exact:true}).selectOption(match.match_ref)
 await page.getByLabel(`${goalName}: Ganar tres partidos`,{exact:true}).fill('0')
 const correcting=page.waitForResponse(r=>r.url().includes('/objective-journal/')&&r.request().method()==='PUT')
 await page.getByRole('button',{name:'Guardar corrección de esta partida',exact:true}).click()
 expect((await correcting).ok()).toBeTruthy()
 const goals=await (await request.get('/api/objective-planning')).json()
 expect(goals.items.find((g:{id:number})=>g.id===before.id).progress).toEqual(before.progress)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
 await page.screenshot({path:info.outputPath('objective-journal-correction.png'),fullPage:true})
})
