// Synthetic text rendered to PNG exercises the real OCR service. It is not an EA capture.
import {test,expect,type Page} from '@playwright/test'
const positions=['POR','LD','DFC','DFC','LI','MC','MC','MC','ED','DC','EI']
async function png(page:Page,text:string){
 const data=await page.evaluate(text=>{const canvas=document.createElement('canvas');canvas.width=1000;canvas.height=100+text.split('\n').length*54;const ctx=canvas.getContext('2d')!;ctx.fillStyle='white';ctx.fillRect(0,0,canvas.width,canvas.height);ctx.fillStyle='black';ctx.font='32px monospace';text.split('\n').forEach((line,i)=>ctx.fillText(line,30,55+i*54));return canvas.toDataURL('image/png').split(',')[1]},text)
 return {name:'pantalla-sintetica.png',mimeType:'image/png',buffer:Buffer.from(data,'base64')}
}
async function upload(page:Page,text:string,scope:string,label:string){
 await page.getByRole('combobox',{name:'Ámbito de lectura',exact:true}).selectOption(scope)
 await page.getByLabel('Página o ubicación',{exact:true}).fill(label)
 await page.getByLabel('Adjuntar captura',{exact:true}).setInputFiles(await png(page,text))
 const response=page.waitForResponse(r=>r.url().includes('/assisted/sessions/')&&r.url().endsWith('/read'))
 await page.getByRole('button',{name:'Leer pantalla',exact:true}).click()
 const read=await response;expect(read.ok()).toBeTruthy();return read.json()
}
async function reviewCards(page:Page,reading:any,slots?:Record<string,string>){
 await page.getByRole('button',{name:'Revisar lectura',exact:true}).click()
 await page.getByLabel('Revisé que corresponde a FC27 y a este contexto de club').check()
 await page.getByLabel('Formación visible',{exact:true}).fill('4-3-3')
 const counts:Record<string,number>={}
 for(const c of reading.original.cards){const n=c.ordinal+1;counts[c.position]=(counts[c.position]||0)+1
  await page.getByLabel(`Variante visible ${n}`,{exact:true}).fill('Oro común')
  await page.getByRole('combobox',{name:`Cesión ${n}`,exact:true}).selectOption('false')
  await page.getByLabel(`Puesto observado ${n}`,{exact:true}).fill(slots?.[c.name]||`${c.position}-${counts[c.position]}`)
 }
 await page.getByLabel('Escribe GUARDAR OBSERVACION',{exact:true}).fill('GUARDAR OBSERVACION')
 const response=page.waitForResponse(r=>r.url().endsWith(`/assisted/readings/${reading.id}/review`))
 await page.getByRole('button',{name:'Guardar observación',exact:true}).click()
 expect((await response).ok()).toBeTruthy()
}
