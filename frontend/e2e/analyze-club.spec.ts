import {test,expect,openLocal} from './fixtures'

test('Analizar mi club calcula, muestra el permiso pendiente y conserva un recorrido cancelable',async({page},info)=>{
 await openLocal(page)
 const analysis=page.getByRole('region',{name:'Analizar mi club',exact:true})
 await analysis.getByRole('button',{name:'Analizar mi club',exact:true}).click()
 await expect(analysis.getByRole('list',{name:'Progreso del análisis'})).toBeVisible({timeout:30000})
 await expect(analysis.getByText('Comprobando permiso y contexto',{exact:true})).toBeVisible()
 await expect(analysis.getByRole('heading',{name:'Mis cartas observadas'})).toBeVisible()
 await expect(analysis.getByText(/Pulsa el icono de la extensión/).first()).toBeVisible()
 await expect(analysis.getByText('Principal local sin cambios',{exact:false})).toBeVisible()
 await analysis.getByRole('button',{name:'Pausar lectura'}).click()
 await expect(analysis.getByRole('heading',{name:'Análisis pausado'})).toBeVisible()
 await page.reload()
 await expect(analysis.getByRole('heading',{name:'Análisis pausado'})).toBeVisible()
 await analysis.getByRole('button',{name:'Reanudar análisis'}).click()
 await expect(analysis.getByRole('button',{name:'Pausar lectura'})).toBeVisible()
 await analysis.getByRole('button',{name:'Cancelar recorrido'}).click()
 await expect(analysis.getByRole('heading',{name:'Análisis cancelado'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:info.outputPath('analyze-club.png'),fullPage:true})
 await page.evaluate(()=>scrollTo(0,0))
 await page.screenshot({path:info.outputPath('analyze-club-viewport.png'),fullPage:false})
})
