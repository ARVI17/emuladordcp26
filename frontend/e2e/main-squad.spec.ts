import {test,expect,openLocal,go} from './fixtures'

test('principal revisada, filtros DCP y equipo de objetivos conservan las mismas copias y progreso',async({page,request},testInfo)=>{
 test.setTimeout(90000)
 const stamp=Date.now(),name=`Principal sintética ${stamp}`
 const recommendation=await (await request.post('/api/squads/recommend',{data:{bench_size:7}})).json()
 const saved=await request.post('/api/squads',{data:{name,formation:recommendation.formation,player_ids:[...recommendation.lineup.map((m:any)=>m.player.id),...recommendation.bench.map((p:any)=>p.id)],slots:[...recommendation.lineup.map((m:any)=>m.slot),...recommendation.bench.map((_:any,i:number)=>`BENCH-${i+1}`)]}})
 expect(saved.ok()).toBeTruthy()
 const squad=await saved.json()
 await openLocal(page)
 await go(page,'Mi club')
 await expect(page.getByRole('heading',{name:'Mi club',exact:true})).toBeVisible()
 await go(page,'Plantillas')
 const protection=page.getByRole('region',{name:'Protección de la principal'})
 await protection.getByText('Revisar cambio de principal',{exact:true}).click()
 await protection.getByLabel('Plantilla principal elegida').selectOption(String(squad.id))
 await protection.getByLabel('He revisado el once y he incluido todo su banquillo y reservas.').check()
 await protection.getByLabel(`Escribe PROTEGER PRINCIPAL ${squad.id}`).fill(`PROTEGER PRINCIPAL ${squad.id}`)
 const selection=page.waitForResponse(r=>r.url().endsWith(`/squads/${squad.id}/main`)&&r.request().method()==='POST')
 await protection.getByRole('button',{name:'Proteger esta principal'}).click()
 expect((await selection).ok()).toBeTruthy()
 const before=await (await request.get('/api/squads/main')).json()
 const primaryCard=squad.players[0].player.id
 expect((await request.delete(`/api/players/${primaryCard}`)).status()).toBe(409)
 await page.reload()
 await expect(page.getByText(/Registro local sin vincular · Simulaciones/)).toBeVisible()
 await go(page,'DCP')
 await page.getByText(/Protegidas: no se usarán/).click()
 await expect(page.getByText(/Plantilla principal o reservas conservadas/).first()).toBeVisible()
 await page.getByText('Filtrar cartas y guardar preferencias',{exact:true}).click()
 await page.getByLabel('Media máxima',{exact:true}).fill('85')
 await page.getByRole('button',{name:'Guardar filtros DCP'}).click()
 await expect(page.getByRole('status').filter({hasText:'Filtros guardados.'})).toBeVisible()
 expect((await (await request.get('/api/dcp/preferences')).json()).max_rating).toBe(85)
 await go(page,'Centro FC')
 await page.getByRole('button',{name:'+ Transcribir objetivo',exact:true}).click()
 const goalName=`Objetivo sintético ${stamp}`
 await page.getByLabel('Nombre del objetivo',{exact:true}).fill(goalName)
 await page.getByLabel('Fuente o referencia',{exact:true}).fill('Fuente sintética de prueba E2E')
 await page.getByLabel('Texto original completo',{exact:true}).fill('Una carta de media 75 o más en el once; disputar dos partidos sintéticos.')
 await page.getByLabel('Meta del contador',{exact:true}).fill('2')
 await page.getByLabel('Vencimiento conocido',{exact:true}).fill(new Date(Date.now()-3*3600000).toISOString().slice(0,16))
 await page.getByRole('combobox',{name:'Modalidad',exact:true}).selectOption('squad_battles')
 await page.getByRole('combobox',{name:'Dificultad mínima',exact:true}).selectOption('professional')
 await page.getByRole('combobox',{name:'Cesiones permitidas',exact:true}).selectOption('false')
 await page.getByRole('button',{name:'Añadir condición',exact:true}).click()
 await page.getByLabel('Texto de condición 1',{exact:true}).fill('Al menos una carta de media 75 en el once')
 await page.getByRole('combobox',{name:'Campo de condición 1',exact:true}).selectOption('rating')
 await page.getByRole('combobox',{name:'Comparación de condición 1',exact:true}).selectOption('ge')
 await page.getByLabel('Valor de condición 1',{exact:true}).fill('75')
 await page.getByLabel('Revisé la interpretación de condición 1',{exact:true}).check()
 await page.getByRole('button',{name:'Añadir acción de partido',exact:true}).click()
 await page.getByLabel('Cantidad de acción 1',{exact:true}).fill('2')
 await page.getByLabel('Texto de acción 1',{exact:true}).fill('Disputar dos partidos según la regla sintética')
 await page.getByLabel('Revisé la transcripción y sus límites; sigue siendo manual',{exact:true}).check()
 await page.getByLabel('Escribe REVISAR OBJETIVO',{exact:true}).fill('REVISAR OBJETIVO')
 const createGoal=page.waitForResponse(r=>r.url().endsWith('/api/objective-planning')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'Guardar reglas auxiliares',exact:true}).click()
 const createdGoal=await createGoal
 expect(createdGoal.ok()).toBeTruthy()
 const goal=await createdGoal.json()
 expect(goal.progress.value).toBeNull()
 expect(goal.definition_verified).toBeFalsy()
 await page.getByRole('button',{name:'Crear plantilla para estos objetivos',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Plantillas para objetivos',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Comparar plantillas propias',exact:true}).click()
 await expect(page.getByText('Composición lista según las reglas revisadas',{exact:true}).first()).toBeVisible()
 await expect(page.getByText(/Pendiente de comprobar en partido/).first()).toBeVisible()
 await expect(page.getByText(/Reglas auxiliares manuales: vigencia oficial no acreditada/).first()).toBeVisible()
 const exported=page.waitForEvent('download')
 await page.getByRole('button',{name:'Exportar lista A',exact:true}).click()
 expect((await exported).suggestedFilename()).toBe('plantilla-objetivos-FC27.json')
 await page.locator('.objective-proposal').first().screenshot({path:testInfo.outputPath('objetivos-composicion.png')})
 await page.getByRole('button',{name:'Guardar alternativa A',exact:true}).click()
 await expect(page.getByText(/Alternativa #\d+ guardada/)).toBeVisible()
 const goals=await (await request.get('/api/objective-planning')).json()
 expect(goals.items.find((row:any)=>row.id===goal.id).progress.value).toBeNull()
 await go(page,'Plantillas')
 await expect(page.getByRole('heading',{name:'Mi plantilla principal',exact:true,level:2})).toBeVisible()
 const after=await (await request.get('/api/squads/main')).json()
 expect(after).toEqual(before)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:testInfo.outputPath('principal-protegida.png')})
})
