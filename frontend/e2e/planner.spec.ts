test('revisa, reserva y cancela un plan sin consumir la carta',async({page,request},testInfo)=>{
 const name=`Reserva E2E ${Date.now()}`
 const created=await request.post('/api/players',{data:{name,rating:80,position:'MC',league:'Prueba',club:'Prueba',nationality:'CO',price:null}})
 expect(created.ok()).toBeTruthy()
 await openLocal(page)
 await page.getByRole('button',{name:'Planes',exact:true}).click()
 await page.getByLabel('Nombre',{exact:true}).fill(name)
 await page.getByLabel('Copias exactas').fill(name)
 await page.getByRole('button',{name:new RegExp(name)}).click()
 await page.getByRole('button',{name:'Añadir acción a la propuesta'}).click()
 await page.getByRole('button',{name:'Simular propuesta'}).click()
 await expect(page.getByRole('button',{name:'Guardar borrador'})).toBeEnabled()
 const saved=page.waitForResponse(r=>r.url().endsWith('/api/plans')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'Guardar borrador'}).click()
 const plan=await (await saved).json()
 const panel=page.locator('section.panel').filter({has:page.getByRole('heading',{name,exact:true})})
 await panel.getByLabel('Confirmación de la revisión').fill(`REVISAR ${plan.id}`)
 await panel.getByRole('button',{name:'Marcar revisión'}).click()
 await panel.getByRole('button',{name:'Reservar estas copias'}).click()
 await expect(panel.getByText(/1 cartas reservadas/)).toBeVisible()
 await page.screenshot({path:testInfo.outputPath('reserved-plan.png'),fullPage:true})
 await panel.getByRole('button',{name:'Cancelar y liberar reservas'}).click()
 await expect(panel.getByText(/Cancelado/)).toBeVisible()
 const remaining=await request.get(`/api/players?search=${encodeURIComponent(name)}`)
 expect((await remaining.json()).total).toBe(1)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})
